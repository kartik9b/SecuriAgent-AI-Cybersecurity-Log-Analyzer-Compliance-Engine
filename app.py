import streamlit as st
import pandas as pd
import json
import os
from datetime import datetime

# Import mitigation module functions from root
from src_mitigation import execute_simulated_ip_block, get_blocked_ips

st.set_page_config(page_title="SecuriAgent AI | Security Operations Dashboard", layout="wide")

st.title("🛡️ SecuriAgent AI: Cybersecurity Log Analyzer & Compliance Engine")
st.markdown("Autonomous cybersecurity log analysis, genuine ML anomaly detection, ISO 27001/NIST CSF compliance mapping, and sandbox firewall mitigation.")

# Sidebar controls
st.sidebar.header("Control Panel")
uploaded_file = st.sidebar.file_uploader("Upload Security Log File (CSV)", type=["csv"])

# --- TAB SETUP ---
tab1, tab2, tab3 = st.tabs(["📊 Live Analysis & Incidents", "🤖 Model Training Metrics", "🧱 Firewall Sandbox"])

with tab1:
    if uploaded_file is not None:
        st.success("Log file uploaded successfully!")
        
        if st.button("Run Security Analysis Pipeline"):
            with st.spinner("Executing model inference and alert correlation..."):
                df = pd.read_csv(uploaded_file)
                
                # Metrics Row
                col1, col2, col3 = st.columns(3)
                col1.metric("Total Logs Processed", len(df))
                col2.metric("Anomalies Flagged", int((df["failure_count"] > 3).sum() | (df["event_type"].isin(["PORT_SCAN", "SQL_INJECTION"]))))
                col3.metric("High-Risk Source IPs", len(df["source_ip"].unique()))
                
                st.divider()
                
                st.subheader("🚨 Correlated Security Incidents & Mitigation Sandbox")
                suspicious_df = df[(df["failure_count"] > 3) | (df["event_type"].isin(["PORT_SCAN", "SQL_INJECTION"]))]
                
                if not suspicious_df.empty:
                    # Display dataframe of incidents
                    st.dataframe(suspicious_df[["timestamp", "source_ip", "event_type", "failure_count", "status_code"]])
                    
                    st.markdown("### ⚡ Interactive Response Action (Sandbox Firewall)")
                    selected_ip = st.selectbox("Select Source IP to Mitigate:", options=suspicious_df["source_ip"].unique())
                    selected_reason = st.text_input("Mitigation Reason / Policy Violation", value="Anomalous behavior or unauthorized threat signature detected.")
                    
                    if st.button("🛡️ Execute Simulated Firewall Block"):
                        result = execute_simulated_ip_block(selected_ip, selected_reason)
                        if result["status"] == "SUCCESS":
                            st.success(f"✅ {result['message']} at {result['timestamp']}")
                        else:
                            st.warning(f"⚠️ {result['message']}")
                else:
                    st.info("No critical security incidents detected in this batch.")
                    
                st.divider()
                
                st.subheader("📋 Compliance Mapping (ISO 27001 & NIST CSF)")
                compliance_data = [
                    {"Event Type": "LOGIN_FAILURE", "NIST CSF": "PR.AC-1 (Access Control)", "ISO 27001": "A.9.4.2 (Secure Log-on)", "Remediation": "Enforce account lockouts after 5 failed attempts."},
                    {"Event Type": "PORT_SCAN", "NIST CSF": "DE.CM-1 (Network Monitoring)", "ISO 27001": "A.13.1.1 (Network Controls)", "Remediation": "Block source IP via firewall rules."},
                    {"Event Type": "SQL_INJECTION", "NIST CSF": "PR.DS-5 (Data Protection)", "ISO 27001": "A.14.1.2 (Application Security)", "Remediation": "Implement parameterized queries and WAF filters."}
                ]
                st.table(pd.DataFrame(compliance_data))
                
                st.success("Analysis complete! Executive report ready for download.")
                
                # Executive Report Markdown
                report_content = f"""# EXECUTIVE SECURITY INCIDENT REPORT
**Generated by:** SecuriAgent AI  
**Candidate Name:** Kartik Bingi  
**Assessment:** Kapstone AI/ML Developer Intern Technical Assessment  

## 1. Summary Metrics
- **Total Logs Analyzed:** {len(df)}
- **Anomalies Flagged:** {len(suspicious_df)}
- **Unique Source IPs Evaluated:** {len(df["source_ip"].unique())}

## 2. Mitigation Actions Taken
- **Sandbox Firewall Rules Applied:** Active IP block rules logged to `sandbox/firewall_rules.json`.
"""

                st.download_button(
                    label="📥 Download Executive Security Report (Markdown)",
                    data=report_content,
                    file_name="security_incident_report.md",
                    mime="text/markdown"
                )
    else:
        st.info("Please upload a security log CSV file via the sidebar to begin analysis (you can use `data/raw_logs.csv` generated from `src_model.py`).")

with tab2:
    st.subheader("🤖 Isolation Forest Model Evaluation Metrics")
    metrics_path = "models/evaluation_metrics.json"
    if os.path.exists(metrics_path):
        with open(metrics_path, "r") as f:
            metrics = json.load(f)
            
        m1, m2, m3 = st.columns(3)
        m1.metric("Precision (Unseen Test)", metrics["precision"])
        m2.metric("Recall (Unseen Test)", metrics["recall"])
        m3.metric("F1-Score (Unseen Test)", metrics["f1_score"])
        
        st.success("Model was genuinely trained, evaluated on an unseen 30% test split, and serialized successfully.")
    else:
        st.warning("Model metrics file not found. Please run `python src_model.py` first to train the model and generate evaluation metrics.")

with tab3:
    st.subheader("🧱 Sandbox Firewall Blocklist Monitor")
    blocked_ips = get_blocked_ips()
    if blocked_ips:
        st.write("The following IP addresses are currently blocked in the simulated sandbox firewall:")
        st.table(pd.DataFrame(blocked_ips))
    else:
        st.info("No IP addresses are currently blocked in the sandbox firewall rules table.")